export const getVideoById = (id: string): Video | undefined => {
  return videos.find(v => v.id === id);
};

export const getVideosByCategory = (category: string): Video[] => {
  if (category === 'all') return videos;
  return videos.filter(v => v.category === category);
};

export const getVideosByMovement = (category: string, movement: string): Video[] => {
  return videos.filter(v => v.category === category && v.movement === movement);
};

export const getRelatedVideos = (id: string, limit: number = 4): Video[] => {
  const currentVideo = getVideoById(id);
  if (!currentVideo) return videos.slice(0, limit);
  // 优先推荐同品类同动作的视频，其次同品类
  const sameMovement = videos.filter(v => v.id !== id && v.movement === currentVideo.movement);
  if (sameMovement.length >= limit) return sameMovement.slice(0, limit);
  const sameCategory = videos.filter(v => v.id !== id && v.category === currentVideo.category && v.movement !== currentVideo.movement);
  return [...sameMovement, ...sameCategory].slice(0, limit);
};
